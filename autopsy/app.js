// --- Rules: how a name gets classified. Order matters — first match wins. ---
// `stop: true` means "don't bother listing what's inside this, just total it
// up as one item" — that's what keeps a node_modules folder with 40,000 tiny
// files from turning into 40,000 rows on screen.
const LARGE_FILE_BYTES = 300 * 1024 * 1024;

const RULES = [
  { test: (n) => n === '.Trash' || n === '.Trashes', category: 'Trash', level: 'safe', reason: 'Already in the Trash — safe to empty.', stop: true },
  { test: (n) => n === 'node_modules' || n === 'bower_components', category: 'JS dependencies', level: 'safe', reason: 'Regenerated automatically by running "npm install" again.', stop: true },
  { test: (n) => n === '.venv' || n === 'venv' || n === 'env', category: 'Python virtual environment', level: 'safe', reason: 'Regenerated by recreating the virtual environment and reinstalling.', stop: true },
  { test: (n) => n === '__pycache__' || n === '.pytest_cache' || n === '.mypy_cache' || n === '.ruff_cache', category: 'Python cache', level: 'safe', reason: 'Rebuilt automatically the next time the code runs.', stop: true },
  { test: (n) => n === 'DerivedData', category: 'Xcode build cache', level: 'safe', reason: 'Xcode regenerates this the next time you build a project.', stop: true },
  { test: (n) => n === 'iOS DeviceSupport' || n === 'watchOS DeviceSupport' || n === 'tvOS DeviceSupport', category: 'Old device symbol files', level: 'review', reason: 'Xcode debugging files for a specific OS version on a real device — re-downloaded automatically next time you connect that device, but only if you still develop for it.', stop: true },
  { test: (n) => n === '.npm' || n === '.gradle' || n === '.cocoapods' || n === '.cache', category: 'Package manager cache', level: 'safe', reason: 'Re-downloaded automatically the next time you install packages.', stop: true },
  { test: (n) => n === 'Caches' || n === 'CachedData' || n === 'CacheStorage' || /Cache$/.test(n), category: 'App cache', level: 'safe', reason: "Temporary data an app rebuilds on its own — deleting it just means the app is slightly slower the next time it opens.", stop: true },
  { test: (n) => n === 'DiagnosticReports', category: 'Crash & diagnostic reports', level: 'safe', reason: "Historical crash logs macOS keeps for its own reference — safe to clear, nothing reads them after the fact unless you're actively debugging a crash.", stop: true },
  { test: (n) => n === 'Logs', category: 'Log files', level: 'safe', reason: 'Old app/system log files — apps just start a fresh one next time; nothing relies on the history.', stop: true },
  { test: (n) => n === 'Saved Application State', category: 'Window-restore state', level: 'safe', reason: "Remembers which windows/tabs each app had open — safe to clear, it just means apps won't restore their previous layout next time they launch.", stop: true },
  { test: (n) => n === 'MobileSync', category: 'iPhone/iPad backups', level: 'review', reason: "Old Finder/iTunes device backups — these hide here and can be tens of GB each. Check Finder → your device → Manage Backups before deleting; keep at least your most recent one.", stop: true },
  { test: (n) => n === 'WebKit', category: 'Safari website data', level: 'review', reason: "Safari's per-site storage — closer to \"cookies\" than a disposable cache. Clearing it frees space but signs you out of sites and can lose offline web-app data.", stop: true },
  { test: (n) => n === 'Cookies.binarycookies', category: 'Safari cookies', level: 'review', reason: 'Every saved Safari login in one file — deleting it signs you out of everything. Usually only a few MB, so rarely worth it just for space.' },
  { test: (n) => n === 'Docker.raw' || n === 'Docker.qcow2', category: 'Docker Desktop virtual disk', level: 'review', reason: "Docker Desktop's own virtual disk — grows over time as you pull images. Shrink it from Docker Desktop's settings (Resources → Disk image size) rather than deleting this file directly." },
  { test: (n) => /\.app$/.test(n), category: 'Application', level: 'keep', reason: "Drag it from Applications to the Trash to uninstall — don't delete files inside it directly.", stop: true },
  { test: (n) => /\.photoslibrary$/.test(n), category: 'Photos library', level: 'keep', reason: 'Your photo library — treat as precious.', stop: true },
  { test: (n) => /\.(imovielibrary|fcpbundle)$/.test(n), category: 'Video library', level: 'keep', reason: 'Video editing project data — treat as precious.', stop: true },
  { test: (n) => /\.musiclibrary$/.test(n), category: 'Music library', level: 'keep', reason: 'Your music library — treat as precious.', stop: true },
  { test: (n) => /\.(sparsebundle|dmg|iso)$/i.test(n), category: 'Disk image', level: 'review', reason: 'Often a leftover installer — check whether you still need it.', stop: true },
  { test: (n) => /\.(vmdk|vdi|vhd)$/i.test(n), category: 'Virtual machine disk', level: 'review', reason: 'Large VM disk — keep only if that virtual machine is still in use.', stop: true },
];

function matchRule(name) {
  for (const rule of RULES) {
    if (rule.test(name)) return rule;
  }
  return null;
}

// --- Scanning ---

const stats = { items: 0, skipped: 0 };
let scanTicker = null;

// `onDiscover` is a hook the live scan-in-progress visualization plugs into
// (see the "Live scan visualization" section) — a no-op by default so the
// scan engine has zero cost when nothing is listening. Kept as a single
// swappable function rather than an event bus since there's only ever one
// listener at a time.
let onDiscover = () => {};

async function sumSizeOnly(dirHandle, depth, topName) {
  let total = 0;
  for await (const [name, handle] of dirHandle.entries()) {
    try {
      if (handle.kind === 'file') {
        if (name === '.DS_Store') continue;
        const file = await handle.getFile();
        total += file.size;
        stats.items++;
        onDiscover({ name, size: file.size, flag: null, depth: depth + 1, topName });
      } else {
        total += await sumSizeOnly(handle, depth + 1, topName);
      }
    } catch {
      stats.skipped++;
    }
  }
  return total;
}

async function scanEntry(handle, name, depth, forceFull, topName) {
  if (handle.kind === 'file') {
    if (name === '.DS_Store') return null;
    const file = await handle.getFile();
    stats.items++;
    const rule = matchRule(name);
    let flag = null;
    if (rule) {
      flag = { category: rule.category, level: rule.level, reason: rule.reason };
    } else if (file.size > LARGE_FILE_BYTES) {
      flag = { category: 'Large file', level: 'review', reason: "Big enough to be worth checking — an old installer, export, or backup you may not need." };
    }
    onDiscover({ name, size: file.size, flag, depth, topName });
    return { name, kind: 'file', size: file.size, flag, children: [] };
  }

  const rule = !forceFull ? matchRule(name) : null;
  if (rule && rule.stop) {
    const size = await sumSizeOnly(handle, depth, topName);
    const flag = { category: rule.category, level: rule.level, reason: rule.reason };
    onDiscover({ name, size, flag, depth, topName });
    return { name, kind: 'directory', size, flag, children: [], stopped: true };
  }

  const children = [];
  let size = 0;
  for await (const [childName, childHandle] of handle.entries()) {
    try {
      const childTop = depth === 0 ? childName : topName;
      const node = await scanEntry(childHandle, childName, depth + 1, false, childTop);
      if (node) {
        children.push(node);
        size += node.size;
      }
    } catch {
      stats.skipped++;
    }
  }
  children.sort((a, b) => b.size - a.size);
  const hasFlaggedDescendant = children.some((c) => c.flag || c.hasFlaggedDescendant);
  const dirNode = { name, kind: 'directory', size, flag: rule ? { category: rule.category, level: rule.level, reason: rule.reason } : null, children, hasFlaggedDescendant };
  // Parent pointers are only needed for the sunburst's breadcrumb/zoom-out —
  // set once here rather than re-derived, since nothing else needs to walk
  // upward through the tree.
  children.forEach((c) => { c.parent = dirNode; });
  onDiscover({ name, size, flag: dirNode.flag, depth, topName });
  return dirNode;
}

// --- Formatting ---

function formatBytes(bytes) {
  if (bytes < 1024) return bytes + ' B';
  const units = ['KB', 'MB', 'GB', 'TB'];
  let val = bytes;
  let i = -1;
  do { val /= 1024; i++; } while (val >= 1024 && i < units.length - 1);
  return val.toFixed(val >= 10 || i === 0 ? 0 : 1) + ' ' + units[i];
}

const ICONS = { file: '📄', directory: '📁' };

// --- Rendering ---

let forest = []; // top-level scanned roots
let activeFilter = 'all';

function nodeMatchesFilter(node, filter) {
  if (filter === 'all') return true;
  return node.flag && node.flag.level === filter;
}

function nodeVisibleUnderFilter(node, filter) {
  if (filter === 'all') return true;
  if (nodeMatchesFilter(node, filter)) return true;
  return node.children.some((c) => nodeVisibleUnderFilter(c, filter));
}

function renderNode(node, depth, filter) {
  if (!nodeVisibleUnderFilter(node, filter)) return null;

  const row = document.createElement('div');
  row.className = 'node-row';
  const hasChildren = node.children.length > 0;
  if (hasChildren) row.classList.add('expandable');
  row.style.paddingLeft = 12 + depth * 20 + 'px';

  const caret = document.createElement('span');
  caret.className = 'node-caret';
  caret.textContent = hasChildren ? '▶' : '';
  row.appendChild(caret);

  const icon = document.createElement('span');
  icon.className = 'node-icon';
  icon.textContent = ICONS[node.kind];
  row.appendChild(icon);

  const nameWrap = document.createElement('div');
  nameWrap.className = 'node-name-wrap';
  const nameEl = document.createElement('div');
  nameEl.className = 'node-name';
  nameEl.textContent = node.name + (node.stopped ? ' /' : '');
  nameWrap.appendChild(nameEl);
  if (node.flag) {
    const reasonEl = document.createElement('div');
    reasonEl.className = 'node-reason';
    reasonEl.textContent = node.flag.reason;
    nameWrap.appendChild(reasonEl);
  }
  row.appendChild(nameWrap);

  const verdict = document.createElement('div');
  verdict.className = 'node-verdict';
  if (node.flag) {
    const badge = document.createElement('span');
    badge.className = 'badge badge-' + node.flag.level;
    badge.textContent = node.flag.level === 'safe' ? 'Safe to delete' : node.flag.level === 'review' ? 'Worth a look' : 'Keep';
    verdict.appendChild(badge);
  }
  row.appendChild(verdict);

  const sizeEl = document.createElement('div');
  sizeEl.className = 'node-size';
  sizeEl.textContent = formatBytes(node.size);
  row.appendChild(sizeEl);

  const wrapper = document.createElement('div');
  wrapper.appendChild(row);

  if (hasChildren) {
    const childrenWrap = document.createElement('div');
    childrenWrap.className = 'node-children';
    for (const child of node.children) {
      const childEl = renderNode(child, depth + 1, filter);
      if (childEl) childrenWrap.appendChild(childEl);
    }

    const shouldAutoOpen = filter !== 'all' || (depth < 4 && node.hasFlaggedDescendant);
    if (shouldAutoOpen) {
      childrenWrap.classList.add('open');
      caret.classList.add('open');
    }

    row.addEventListener('click', () => {
      childrenWrap.classList.toggle('open');
      caret.classList.toggle('open');
    });

    wrapper.appendChild(childrenWrap);
  }

  return wrapper;
}

function renderTree() {
  const tree = document.getElementById('tree');
  tree.innerHTML = '';
  for (const root of forest) {
    const el = renderNode(root, 0, activeFilter);
    if (el) tree.appendChild(el);
  }
}

// --- Sunburst ---
// A radial hierarchy chart: rings = folder depth, arc angle = share of the
// parent's size, color = verdict. Chosen over a flat list as the primary
// view because "which branch is way bigger than its siblings" is exactly
// what this shape is good at — precise comparison of close values stays
// the List view's job (see the dataviz skill's guidance on part-to-whole
// charts), which is why that view is kept as an equal, always-available
// alternative rather than being replaced.

const SUNBURST_FILL = { safe: 'var(--fill-safe)', review: 'var(--fill-review)', keep: 'var(--fill-keep)' };
const RING_WIDTH = 40;
const CENTER_RADIUS = 46;
const MAX_RINGS = 4;
const MAX_CHILDREN_PER_RING = 7;

let focusNode = null;

function getSunburstRoot() {
  if (forest.length === 0) return null;
  if (forest.length === 1) return forest[0];
  const total = forest.reduce((sum, r) => sum + r.size, 0);
  const wrapper = { name: 'All scans', size: total, flag: null, children: forest };
  forest.forEach((r) => { r.parent = wrapper; });
  return wrapper;
}

function resetSunburstFocus() {
  focusNode = getSunburstRoot();
}

function fillForNode(node) {
  if (node.flag) return SUNBURST_FILL[node.flag.level] || 'var(--fill-neutral)';
  return 'var(--fill-neutral)';
}

function polarToXY(cx, cy, r, angle) {
  return [cx + r * Math.cos(angle), cy + r * Math.sin(angle)];
}

function arcPath(cx, cy, innerR, outerR, a0, a1) {
  const largeArc = a1 - a0 > Math.PI ? 1 : 0;
  const [x1, y1] = polarToXY(cx, cy, outerR, a0);
  const [x2, y2] = polarToXY(cx, cy, outerR, a1);
  const [x3, y3] = polarToXY(cx, cy, innerR, a1);
  const [x4, y4] = polarToXY(cx, cy, innerR, a0);
  return `M ${x1} ${y1} A ${outerR} ${outerR} 0 ${largeArc} 1 ${x2} ${y2} L ${x3} ${y3} A ${innerR} ${innerR} 0 ${largeArc} 0 ${x4} ${y4} Z`;
}

function layoutRing(node, depth, a0, a1, out) {
  if (depth > MAX_RINGS || !node.children || node.children.length === 0) return;
  const kids = node.children.filter((c) => c.size > 0).sort((a, b) => b.size - a.size);
  let shown = kids;
  let otherSize = 0;
  let otherCount = 0;
  if (kids.length > MAX_CHILDREN_PER_RING) {
    shown = kids.slice(0, MAX_CHILDREN_PER_RING - 1);
    const rest = kids.slice(MAX_CHILDREN_PER_RING - 1);
    otherCount = rest.length;
    otherSize = rest.reduce((sum, c) => sum + c.size, 0);
  }
  const total = node.size || 1;
  const innerR = CENTER_RADIUS + (depth - 1) * RING_WIDTH;
  const outerR = CENTER_RADIUS + depth * RING_WIDTH;
  let cursor = a0;
  for (const child of shown) {
    const span = (child.size / total) * (a1 - a0);
    const seg = { node: child, a0: cursor, a1: cursor + span, innerR, outerR, isOther: false };
    out.push(seg);
    layoutRing(child, depth + 1, seg.a0, seg.a1, out);
    cursor = seg.a1;
  }
  if (otherCount > 0) {
    const span = (otherSize / total) * (a1 - a0);
    out.push({
      node: { name: `+${otherCount} smaller item${otherCount === 1 ? '' : 's'}`, size: otherSize, flag: null, children: [] },
      a0: cursor,
      a1: cursor + span,
      innerR,
      outerR,
      isOther: true,
    });
  }
}

function showTooltip(evt, node) {
  const box = document.getElementById('tooltip');
  box.innerHTML = '';
  const nameEl = document.createElement('div');
  nameEl.className = 'tooltip-name';
  nameEl.textContent = node.name;
  const sizeEl = document.createElement('div');
  sizeEl.className = 'tooltip-size';
  sizeEl.textContent = formatBytes(node.size);
  box.appendChild(nameEl);
  box.appendChild(sizeEl);
  if (node.flag) {
    const badge = document.createElement('div');
    badge.className = 'badge badge-' + node.flag.level + ' tooltip-badge';
    badge.textContent = node.flag.level === 'safe' ? 'Safe to delete' : node.flag.level === 'review' ? 'Worth a look' : 'Keep';
    box.appendChild(badge);
    const reason = document.createElement('div');
    reason.className = 'tooltip-reason';
    reason.textContent = node.flag.reason;
    box.appendChild(reason);
  }
  box.hidden = false;
  let x, y;
  if (evt.type === 'focus') {
    const r = evt.target.getBoundingClientRect();
    x = r.left + r.width / 2;
    y = r.top - 8;
  } else {
    x = evt.clientX + 16;
    y = evt.clientY + 16;
  }
  box.style.left = x + 'px';
  box.style.top = y + 'px';
}

function hideTooltip() {
  document.getElementById('tooltip').hidden = true;
}

function zoomTo(node) {
  focusNode = node;
  renderSunburst();
}

function renderCenter() {
  const el = document.getElementById('sunburstCenter');
  el.innerHTML = '';
  const nameEl = document.createElement('div');
  nameEl.className = 'sunburst-center-name';
  nameEl.textContent = focusNode.name;
  const sizeEl = document.createElement('div');
  sizeEl.className = 'sunburst-center-size';
  sizeEl.textContent = formatBytes(focusNode.size);
  el.appendChild(nameEl);
  el.appendChild(sizeEl);
  if (focusNode.parent) {
    el.classList.add('clickable');
    el.title = 'Zoom out';
    el.onclick = () => zoomTo(focusNode.parent);
  } else {
    el.classList.remove('clickable');
    el.onclick = null;
    el.title = '';
  }
}

function renderBreadcrumb() {
  const el = document.getElementById('breadcrumb');
  el.innerHTML = '';
  const chain = [];
  for (let n = focusNode; n; n = n.parent) chain.unshift(n);
  chain.forEach((node, i) => {
    const isLast = i === chain.length - 1;
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'crumb' + (isLast ? ' crumb-current' : '');
    btn.textContent = node.name;
    if (isLast) {
      btn.disabled = true;
    } else {
      btn.addEventListener('click', () => zoomTo(node));
    }
    el.appendChild(btn);
    if (!isLast) {
      const sep = document.createElement('span');
      sep.className = 'crumb-sep';
      sep.textContent = '›';
      el.appendChild(sep);
    }
  });
}

function renderSunburst() {
  const svg = document.getElementById('sunburstSvg');
  svg.innerHTML = '';
  if (!focusNode) return;

  const cx = 260, cy = 260;
  const segments = [];
  layoutRing(focusNode, 1, -Math.PI / 2, -Math.PI / 2 + Math.PI * 2, segments);

  const ns = 'http://www.w3.org/2000/svg';
  for (const seg of segments) {
    const path = document.createElementNS(ns, 'path');
    path.setAttribute('d', arcPath(cx, cy, seg.innerR, seg.outerR, seg.a0, seg.a1));
    path.setAttribute('class', 'sunburst-arc' + (seg.isOther ? ' sunburst-arc-other' : ''));
    path.style.fill = fillForNode(seg.node);

    if (activeFilter !== 'all' && !(seg.node.flag && seg.node.flag.level === activeFilter)) {
      path.classList.add('dimmed');
    }

    const canZoom = !seg.isOther && seg.node.children && seg.node.children.length > 0;
    if (canZoom) {
      path.classList.add('clickable');
      path.tabIndex = 0;
      path.setAttribute('role', 'button');
      path.setAttribute('aria-label', `${seg.node.name}, ${formatBytes(seg.node.size)}, zoom in`);
      path.addEventListener('click', () => zoomTo(seg.node));
      path.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); zoomTo(seg.node); }
      });
    }
    path.addEventListener('pointermove', (e) => showTooltip(e, seg.node));
    path.addEventListener('pointerleave', hideTooltip);
    path.addEventListener('focus', (e) => showTooltip(e, seg.node));
    path.addEventListener('blur', hideTooltip);
    svg.appendChild(path);
  }

  renderCenter();
  renderBreadcrumb();
}

function sumByLevel(node, level) {
  let total = 0;
  if (node.flag && node.flag.level === level) return node.size;
  for (const child of node.children) total += sumByLevel(child, level);
  return total;
}

function renderSummary() {
  const totalScanned = forest.reduce((sum, r) => sum + r.size, 0);
  const safeTotal = forest.reduce((sum, r) => sum + sumByLevel(r, 'safe'), 0);
  const reviewTotal = forest.reduce((sum, r) => sum + sumByLevel(r, 'review'), 0);

  document.getElementById('statTotal').textContent = formatBytes(totalScanned);
  document.getElementById('statSafe').textContent = formatBytes(safeTotal);
  document.getElementById('statReview').textContent = formatBytes(reviewTotal);
  document.getElementById('statItems').textContent = stats.items.toLocaleString();

  const skippedNote = document.getElementById('skippedNote');
  if (stats.skipped > 0) {
    skippedNote.hidden = false;
    skippedNote.textContent = `${stats.skipped.toLocaleString()} item(s) couldn't be read (permission denied) and were skipped.`;
  } else {
    skippedNote.hidden = true;
  }
}

