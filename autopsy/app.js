function showError(err) {
  const box = document.getElementById('errorNotice');
  if (location.protocol === 'file:') {
    box.textContent = "This can't run when the page is opened directly as a file (the address bar shows file://) — Chrome blocks folder access there for security. Serve this folder locally instead: open Terminal, cd into this folder, run \"python3 -m http.server\", then visit http://localhost:8000 in Chrome. (The version hosted on GitHub Pages, once pushed, won't have this problem.)";
  } else {
    box.textContent = 'Something went wrong: ' + (err && err.message ? err.message : String(err));
  }
  box.hidden = false;
}

async function runScan(startIn) {
  const supported = 'showDirectoryPicker' in window;
  if (!supported) {
    document.getElementById('unsupported').hidden = false;
    return;
  }
  document.getElementById('errorNotice').hidden = true;

  let handle;
  try {
    // `startIn` only points the OS dialog's starting folder — it grants no
    // access by itself. The user still has to pick and confirm a folder,
    // same as any other call.
    handle = await window.showDirectoryPicker(startIn ? { startIn } : undefined);
  } catch (err) {
    if (err && err.name === 'AbortError') return; // user cancelled the picker
    showError(err);
    return;
  }

  document.getElementById('progress').hidden = false;
  document.getElementById('scanBtn').disabled = true;
  scanTicker = setInterval(updateProgressText, 150);
  startLiveViz();

  try {
    const root = await scanEntry(handle, handle.name, 0, true, handle.name);
    forest.push(root);
    forest.sort((a, b) => b.size - a.size);

    document.getElementById('intro').hidden = true;
    document.getElementById('results').hidden = false;
    renderSummary();
    renderTree();
    resetSunburstFocus();
    renderSunburst();
  } catch (err) {
    showError(err);
  } finally {
    clearInterval(scanTicker);
    stopLiveViz();
    document.getElementById('progress').hidden = true;
    document.getElementById('scanBtn').disabled = false;
  }
}

